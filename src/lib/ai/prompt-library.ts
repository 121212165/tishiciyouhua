/** 按分类获取提示词 */
export function getPromptsByCategory(category: PromptCategory): readonly LibraryPrompt[] {
  return PROMPT_LIBRARY.filter((p) => p.category === category)
}

/** 按标签搜索提示词 */
export function searchPromptsByTag(tag: string): readonly LibraryPrompt[] {
  const lower = tag.toLowerCase()
  return PROMPT_LIBRARY.filter((p) => p.tags.some((t) => t.toLowerCase().includes(lower)))
}

/** 按关键词搜索提示词（名称、标签、原始提示词） */
export function searchPrompts(keyword: string): readonly LibraryPrompt[] {
  const lower = keyword.toLowerCase()
  return PROMPT_LIBRARY.filter(
    (p) =>
      p.name.toLowerCase().includes(lower) ||
      p.tags.some((t) => t.toLowerCase().includes(lower)) ||
      p.originalPrompt.toLowerCase().includes(lower)
  )
}

/** 获取所有分类 */
export function getAllCategories(): PromptCategory[] {
  const categories = new Set(PROMPT_LIBRARY.map((p) => p.category))
  return Array.from(categories)
}

/** 获取所有标签（去重） */
export function getAllTags(): string[] {
  const tags = new Set<string>()
  for (const p of PROMPT_LIBRARY) {
    for (const t of p.tags) {
      tags.add(t)
    }
  }
  return Array.from(tags).sort()
}

/** 根据 ID 获取提示词 */
export function getPromptById(id: string): LibraryPrompt | undefined {
  return PROMPT_LIBRARY.find((p) => p.id === id)
}

/** 获取统计数据 */
export function getLibraryStats() {
  const categories = getAllCategories()
  return {
    totalPrompts: PROMPT_LIBRARY.length,
    totalCategories: categories.length,
    totalTags: getAllTags().length,
    byCategory: categories.map((cat) => ({
      category: cat,
      count: getPromptsByCategory(cat).length,
    })),
  }
}

